/**
 * DeepSeek Harness bundle: an npm package declaring `dsh.bundle`. The layer
 * rows that would register the MCP server through @deepseek-ai/dsh-mcp-client
 * are NOT documented upstream, so the patch is a stub until confirmed against
 * a real DSH install (see docs/install/deepseek-harness.md).
 */
import { copySkills, json, mdHeader, skillsTable, type FileSet, type GenerateContext, type WrapperAdapter } from "./types.js";

const DIR = "wrappers/dsh-bundle";

export const dshAdapter: WrapperAdapter = {
  id: "dsh",
  owns: [`${DIR}/`],
  emit(ctx: GenerateContext): FileSet {
    const c = ctx.connector;
    const host = c.hosts.dsh;
    const files: FileSet = new Map();

    files.set(
      `${DIR}/package.json`,
      json({
        name: host.packageName,
        version: c.version,
        description: `${c.displayName} bundle for DeepSeek Harness`,
        license: c.license,
        homepage: c.homepage,
        files: ["cordis.patch.yml", "skills", "README.md"],
        engines: { dsh: host.engines },
        dsh: { bundle: { patch: "./cordis.patch.yml" } },
      }),
    );

    files.set(
      `${DIR}/cordis.patch.yml`,
      `# ${c.displayName} ${c.version}
# GENERATED by scripts/generate-wrappers.ts. Do not edit by hand.
#
# UNCONFIRMED SCHEMA: the row shape that registers an MCP server through
# @deepseek-ai/dsh-mcp-client is not documented upstream. Replace the rows
# below once confirmed against a real DSH install, then update the dsh
# adapter in packages/connector-manifest/src/adapters/dsh.ts.
- insert:
    id: ${c.name}-mcp
    name: "@deepseek-ai/dsh-mcp-client"
    config:
      servers:
        ${c.server.name}:
          url: ${c.server.remote.url}
`,
    );

    files.set(
      `${DIR}/README.md`,
      `${mdHeader()}# ${c.displayName} for DeepSeek Harness

Install into a profile:

\`\`\`bash
dsh plugin --profile <name> add ${host.packageName}
\`\`\`

The bundle registers the \`${c.server.name}\` MCP server (${c.server.remote.url}) and ships these skills:

${skillsTable(ctx)}

> The MCP client row in \`cordis.patch.yml\` is a placeholder until the row schema is confirmed; see the repository's docs/install/deepseek-harness.md.
`,
    );

    copySkills(ctx, `${DIR}/skills`, files);
    return files;
  },
};
