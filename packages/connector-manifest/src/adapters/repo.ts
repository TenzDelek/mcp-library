/** Files inside the repo that must agree with connector.json: version.ts and the JSON schema. */
import { z } from "zod";
import { ConnectorSchema } from "../schema.js";
import { json, type FileSet, type GenerateContext, type WrapperAdapter } from "./types.js";

export const repoAdapter: WrapperAdapter = {
  id: "repo",
  owns: ["packages/connector-server/src/version.ts", "packages/connector-manifest/connector.schema.json"],
  emit(ctx: GenerateContext): FileSet {
    const c = ctx.connector;
    return new Map([
      [
        "packages/connector-server/src/version.ts",
        `// GENERATED by scripts/generate-wrappers.ts from connector.json. Do not edit by hand.
export const VERSION = "${c.version}";
export const SERVER_NAME = "${c.server.name}";
`,
      ],
      ["packages/connector-manifest/connector.schema.json", json(z.toJSONSchema(ConnectorSchema))],
    ]);
  },
};
