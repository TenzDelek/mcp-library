import type { Connector } from "../schema.js";
import type { Skill } from "../skills.js";

export interface ToolInfo {
  name: string;
  title: string;
  description: string;
}

export interface GenerateContext {
  root: string;
  connector: Connector;
  skills: Skill[];
  tools: ToolInfo[];
  instructions: string;
}

/** Repo-relative posix path → file content. */
export type FileSet = Map<string, string>;

/**
 * One adapter per store. `owns` lists the repo-relative roots the adapter
 * fully controls (a directory when it ends with "/", else a single file):
 * generation removes stale files inside them and the drift check reports
 * anything there that a fresh emit would not produce.
 */
export interface WrapperAdapter {
  id: string;
  owns: string[];
  emit(ctx: GenerateContext): FileSet;
}

export const GENERATED_NOTE =
  "GENERATED by scripts/generate-wrappers.ts from connector.json and skills/. Do not edit by hand: run `npm run generate`.";

export function json(value: unknown): string {
  return JSON.stringify(value, null, 2) + "\n";
}

export function mdHeader(): string {
  return `<!-- ${GENERATED_NOTE} -->\n\n`;
}

/** Adds every skill's files under `prefix` (e.g. "wrappers/dsh-bundle/skills"). */
export function copySkills(ctx: GenerateContext, prefix: string, files: FileSet): void {
  for (const skill of ctx.skills) {
    for (const f of skill.files) files.set(`${prefix}/${skill.dirName}/${f.path}`, f.content);
  }
}

export function skillsTable(ctx: GenerateContext): string {
  const rows = ctx.skills.map((s) => `| \`${s.name}\` | ${s.description.replace(/\|/g, "\\|")} | ${s.tools.map((t) => `\`${t}\``).join(", ")} |`);
  return ["| Skill | Use it when | Tools |", "|---|---|---|", ...rows].join("\n");
}

export function toolsTable(ctx: GenerateContext): string {
  const rows = ctx.tools.map((t) => `| \`${t.name}\` | ${t.description.split(". ")[0]!.replace(/\|/g, "\\|")}. |`);
  return ["| Tool | Purpose |", "|---|---|", ...rows].join("\n");
}

export function localServerConfig(ctx: GenerateContext, envValue: string): { command: string; args: string[]; env: Record<string, string> } {
  const { local, name } = ctx.connector.server;
  void name;
  return { command: local.command, args: local.args, env: { [local.envKey]: envValue } };
}
